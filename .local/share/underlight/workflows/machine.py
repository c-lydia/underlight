"""Keep monitor, GPU and project defaults in local named machine profiles."""
import argparse
import json
from pathlib import Path
import re
import subprocess

from .common import atomic_write, choose, config_root, read_json, valid_name, vault_path, write_json


def profile_path(name):
    return config_root() / 'machines' / (valid_name(name) + '.json')


def render(value):
    if value.get('kind') not in ('laptop', 'desktop', 'phone'):
        raise ValueError('Profile kind must be laptop, desktop or phone')
    if value.get('gpu') not in ('auto', 'integrated', 'hybrid'):
        raise ValueError('GPU policy must be auto, integrated or hybrid')
    if value.get('distro') not in ('auto', 'ubuntu', 'endeavouros', 'arch'):
        raise ValueError('Unsupported distro profile')
    monitors = value.get('monitors', [])
    if not isinstance(monitors, list):
        raise ValueError('monitors must be a list')
    lines = ['# Generated by underlight-machine; edit the named JSON profile and apply it.']
    for monitor in monitors:
        if not isinstance(monitor, str) or not re.fullmatch(r'[A-Za-z0-9_ .,+:@/\-]+', monitor) or ',' not in monitor:
            raise ValueError('Monitor rules must be a single Hyprland monitor value, without directives or shell syntax')
        lines.append('monitor = ' + monitor)
    return '\n'.join(lines) + '\n'


def activate(name, preview=False):
    path = profile_path(name)
    if not path.is_file():
        raise ValueError(f'Unknown machine profile: {name}')
    value = read_json(path)
    text = render(value)
    if value.get('vault'):
        vault_path(value['vault'])
    if value.get('project_root') and not Path(value['project_root']).is_dir():
        raise ValueError('The configured project root does not exist on this machine')
    if preview:
        print(json.dumps(value, indent=2))
        print(text)
        return
    value['name'] = name
    changes = {
        config_root() / 'gpu-policy': (value['gpu'] + '\n').encode(),
        config_root() / 'machine.json': (json.dumps(value, indent=2) + '\n').encode(),
    }
    previous = {path: path.read_bytes() if path.exists() else None for path in changes}
    applied = []
    try:
        for path, data in changes.items():
            atomic_write(path, data)
            applied.append(path)
    except Exception:
        for path in reversed(applied):
            if previous[path] is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write(path, previous[path])
        raise
    print(f'Active machine: {name} ({value["kind"]}, {value["distro"]}, GPU {value["gpu"]})')
    if value['kind'] != 'phone':
        print('Apply monitor changes in your desktop session with: hyprctl reload')
    print('GPU policy applies to new underlight-gpu-run launches. Packages and drivers are unchanged.')


def restore_monitors():
    value = read_json(config_root() / 'machine.json')
    if not value:
        return
    render(value)
    if value['kind'] == 'phone':
        return
    for monitor in value.get('monitors', []):
        subprocess.run(['hyprctl', 'keyword', 'monitor', monitor], check=True,
                       capture_output=True, text=True, timeout=5)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    create = sub.add_parser('create')
    create.add_argument('name')
    create.add_argument('--kind', choices=('laptop', 'desktop', 'phone'), required=True)
    create.add_argument('--distro', choices=('auto', 'ubuntu', 'endeavouros', 'arch'), default='auto')
    create.add_argument('--gpu', choices=('auto', 'integrated', 'hybrid'), default='auto')
    create.add_argument('--monitor', action='append', default=[], help='Hyprland monitor value, e.g. eDP-1,preferred,auto,1')
    create.add_argument('--project-root', type=Path)
    create.add_argument('--vault')
    apply = sub.add_parser('apply')
    apply.add_argument('name')
    apply.add_argument('--preview', action='store_true')
    sub.add_parser('list')
    sub.add_parser('status')
    sub.add_parser('restore', help='reapply saved monitor rules at Hyprland login/reload')
    sub.add_parser('menu')
    args = parser.parse_args(argv)
    if args.command == 'create':
        path = profile_path(args.name)
        if path.exists():
            raise ValueError(f'Profile exists; edit {path} to change it')
        value = {'kind': args.kind, 'distro': args.distro, 'gpu': args.gpu, 'monitors': args.monitor}
        if args.project_root:
            value['project_root'] = str(args.project_root.expanduser().resolve())
        if args.vault:
            value['vault'] = str(vault_path(args.vault))
        render(value)
        write_json(path, value)
        print(f'Created {path}. Preview with: underlight-machine apply {args.name} --preview')
    elif args.command == 'apply':
        activate(args.name, args.preview)
    elif args.command == 'status':
        print(json.dumps(read_json(config_root() / 'machine.json'), indent=2))
    elif args.command == 'restore':
        restore_monitors()
    else:
        names = sorted(path.stem for path in (config_root() / 'machines').glob('*.json'))
        if args.command == 'list':
            print('\n'.join(names))
        elif not names:
            raise ValueError('No saved profiles; use underlight-machine create NAME --kind laptop|desktop|phone')
        else:
            selected = choose('Apply machine profile', names)
            if selected:
                activate(selected)
